import { RoleGate } from "@/components/auth/role-gate";
import type { Metadata } from "next";
import { Suspense } from "react";
import { connection } from "next/server";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import { Card } from "@/components/ui/card";
import { DataTable } from "@/components/commerce/data-table";
import {
  WorkspaceEmpty,
  WorkspaceHeading,
  WorkspaceUnavailable,
} from "@/components/commerce/workspace-states";
import { getInvoices } from "@/lib/commerce/data";
import { formatDate, formatMoney } from "@/lib/commerce/format";

export const metadata: Metadata = { title: "Invoices" };
async function InvoicesData() {
  await connection();
  let invoices;
  try {
    invoices = await getInvoices();
  } catch {
    return <WorkspaceUnavailable />;
  }
  if (!invoices.length)
    return (
      <Card>
        <WorkspaceEmpty
          title="A clean slate"
          description="Complete a checkout to create your first draft invoice. Saved invoices will stay here after refresh."
        />
      </Card>
    );
  return (
    <DataTable
      columns={[
        "Invoice / subscription",
        "Customer",
        "Issued",
        "Subtotal",
        "Tax",
        "Total",
        "Status",
      ]}
      caption="Saved workspace invoices"
    >
      {invoices.map((invoice) => (
        <tr key={invoice.id} className="hover:bg-muted/20">
          <td className="max-w-[260px] px-5 py-5">
            <span className="block break-all font-mono text-[10px]">
              {invoice.id}
            </span>
            <span className="mt-1.5 block break-all text-[9px] text-muted-foreground">
              {invoice.subscription.planNumber}
            </span>
          </td>
          <td className="max-w-[200px] break-all px-5 py-5">
            {invoice.subscription.user.email}
          </td>
          <td className="px-5 py-5 whitespace-nowrap text-muted-foreground">
            {formatDate(invoice.issueDate)}
          </td>
          <td className="px-5 py-5">{formatMoney(invoice.subTotal)}</td>
          <td className="px-5 py-5">{formatMoney(invoice.taxAmount)}</td>
          <td className="px-5 py-5 font-semibold">
            {formatMoney(invoice.grandTotal)}
          </td>
          <td className="px-5 py-5">
            <Badge
              variant={
                invoice.status.toUpperCase() === "PAID" ? "success" : "warning"
              }
            >
              {invoice.status}
            </Badge>
          </td>
        </tr>
      ))}
    </DataTable>
  );
}
function InvoicesPageContent() {
  return (
    <div className="page-enter space-y-6">
      <WorkspaceHeading
        title="Every detail, accounted for"
        description="Actual invoices generated by workspace checkout. A draft invoice records an amount due; it does not record a payment."
      />
      <Suspense fallback={<Skeleton className="h-72 w-full" />}>
        <InvoicesData />
      </Suspense>
    </div>
  );
}

export default function InvoicesPage() {
  return (
    <RoleGate roles={["ADMIN", "STAFF"]}>
      <InvoicesPageContent />
    </RoleGate>
  );
}
